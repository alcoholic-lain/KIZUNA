// Builds the pitch deck into ONE self-contained file: mieruka-pitch.html (works offline, from file://).
// Uses esbuild, which ships with Vite and runs on this machine; Rollup is not involved.
//
//   node presentation/build.mjs           build mieruka-pitch.html and PRESENTER-GUIDE.md
//   node presentation/build.mjs --watch   rebuild on every change (refresh the browser)
//
// Run from frontend/ (or anywhere: paths are resolved from this file).
import { build, context } from "esbuild";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "mieruka-pitch.html");
const GUIDE = join(here, "PRESENTER-GUIDE.md");
const watch = process.argv.includes("--watch");

const options = {
  absWorkingDir: here,
  entryPoints: ["src/main.tsx"],
  bundle: true,
  minify: true,
  format: "iife",
  target: ["chrome109", "edge109", "firefox115", "safari16"],
  jsx: "automatic",
  outdir: "out",
  write: false,
  legalComments: "none",
  loader: { ".png": "dataurl", ".svg": "dataurl", ".woff2": "dataurl" },
  define: { "process.env.NODE_ENV": '"production"' },
  logLevel: "warning",
};

function assemble(result) {
  const js = result.outputFiles.find((f) => f.path.endsWith(".js")).text.replace(/<\/script/gi, "<\\/script");
  const css = result.outputFiles.find((f) => f.path.endsWith(".css")).text.replace(/<\/style/gi, "<\\/style");
  const icon = `data:image/svg+xml;base64,${readFileSync(join(here, "../../assets/mieruka/mieruka-app-icon-v8-rounded.svg")).toString("base64")}`;
  const html = readFileSync(join(here, "index.html"), "utf8")
    .replace("__ICON__", () => icon)
    .replace("__CSS__", () => css)
    .replace("__JS__", () => js);
  writeFileSync(OUT, html);
  console.log(`wrote ${OUT} (${(html.length / 1024 / 1024).toFixed(2)} MB)`);
}

async function writeGuide() {
  const tmp = join(here, ".content.tmp.mjs");
  await build({ absWorkingDir: here, entryPoints: ["src/content.ts"], bundle: true, format: "esm", platform: "node", outfile: tmp, logLevel: "warning" });
  const c = await import(`${pathToFileURL(tmp).href}?t=${Date.now()}`);
  rmSync(tmp, { force: true });
  writeFileSync(GUIDE, guide(c));
  console.log(`wrote ${GUIDE}`);
}

const line = (l) => ("say" in l ? l.say : `**[${l.cue}]**${l.note ? ` _${l.note}_` : ""}`);

function guide({ SLIDES, SCRIPT, SHORT, LAST_LINE, BACKUP, DEMO_STEPS, QA, CHECKLIST, words, fmtTime }) {
  const out = [];
  const total = SLIDES.reduce((n, s) => n + words(SCRIPT[s.id]), 0);
  out.push("# Mieruka: presenter guide");
  out.push("");
  out.push("_Generated by `node presentation/build.mjs` from `src/content.ts`, the same file the deck and the presenter window read. Edit the content there, then rebuild._");
  out.push("");
  out.push("KIZUNA 2026, Smart Energy · team Zero-Ichi · five minutes · one presenter.");
  out.push("");
  out.push("## Run of show");
  out.push("");
  out.push("| # | Section | Window | Spoken words | At 150 words/min |");
  out.push("|---|---|---|---|---|");
  SLIDES.forEach((s, i) => {
    const w = words(SCRIPT[s.id]);
    out.push(`| ${i + 1} | ${s.chapter} | ${fmtTime(s.start)}–${fmtTime(s.end)} | ${w} | ${fmtTime((w / 150) * 60)} |`);
  });
  out.push(`| | **Total** | **5:00** | **${total}** | **${fmtTime((total / 150) * 60)}** |`);
  out.push("");
  out.push("The demo window also holds about 15 s of silence while the detector collects three readings, plus the clicks. Slides 1 and 5 each have one build: the first → plays it, the next → moves on.");
  out.push("");
  out.push("## Full script");
  SLIDES.forEach((s, i) => {
    out.push("");
    out.push(`### ${fmtTime(s.start)}–${fmtTime(s.end)} · ${i + 1}. ${s.chapter}`);
    out.push("");
    for (const l of SCRIPT[s.id]) out.push(`${line(l)}`, "");
    out.pop();
  });
  out.push("");
  out.push("## Emergency: the two-minute version");
  out.push("");
  out.push("Use it when the jury asks you to wrap up early. Jump with the slide number keys (shown in brackets).");
  for (const s of SHORT) {
    const i = SLIDES.findIndex((m) => m.id === s.slide);
    out.push("");
    out.push(`**[${i + 1}] ${SLIDES[i].chapter}**`);
    out.push("");
    for (const l of s.lines) out.push(line(l), "");
    out.pop();
  }
  out.push("");
  out.push(`**Cut off mid-sentence?** ${LAST_LINE}`);
  out.push("");
  out.push("## Backup demo (if the live app fails)");
  out.push("");
  out.push("On the demo slide press **B**. Arrows step through seven screenshots recorded from the running prototype on 22 Nov 2026 (simulated data); → on the last one goes on to slide 4, Esc closes. Say the same script; replace “now I simulate” with “here we simulated”.");
  out.push("");
  out.push("| # | Demo step | Screen | What to point at |");
  out.push("|---|---|---|---|");
  BACKUP.forEach((f, i) => {
    out.push(`| ${i + 1} | ${DEMO_STEPS[f.step - 1].title} | ${f.title}: ${f.caption} | ${f.rings.map((r, k) => `(${k + 1}) ${r.label}`).join("; ")} |`);
  });
  out.push("");
  out.push("The PNG files are in `presentation/screens/`. To refresh them, capture the same screens at 1600 × 1000 (CSS pixels), keep the file names, and rebuild. If the layout moved, update the ring coordinates in `src/content.ts`.");
  out.push("");
  out.push("## Jury Q&A");
  for (const q of QA) {
    out.push("");
    out.push(`**${q.q}**`);
    out.push("");
    out.push(q.a);
  }
  out.push("");
  out.push("## Before going on stage");
  out.push("");
  CHECKLIST.forEach((c, i) => out.push(`${i + 1}. ${c}`));
  out.push("");
  return out.join("\n");
}

if (watch) {
  const ctx = await context({
    ...options,
    plugins: [{
      name: "assemble",
      setup(b) {
        b.onEnd(async (r) => {
          if (r.errors.length) return;
          assemble(r);
          await writeGuide().catch((e) => console.error(e.message));
        });
      },
    }],
  });
  await ctx.watch();
  console.log(`watching… open ${pathToFileURL(OUT).href}`);
} else {
  mkdirSync(here, { recursive: true });
  assemble(await build(options));
  await writeGuide();
}
