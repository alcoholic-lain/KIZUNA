def _get_database_config(environ, base_dir):
    uses_persistent_production_database = environ.get("VERCEL_ENV") == "production" and (
        "KIZUNA_TURSO_DATABASE_URL" in environ
        or "KIZUNA_TURSO_AUTH_TOKEN" in environ
    )
    if uses_persistent_production_database:
        database_url = environ.get("KIZUNA_TURSO_DATABASE_URL", "").strip()
        auth_token = environ.get("KIZUNA_TURSO_AUTH_TOKEN", "").strip()
    else:
        database_url = environ.get("TURSO_DATABASE_URL", "").strip()
        auth_token = environ.get("TURSO_AUTH_TOKEN", "").strip()

    if database_url:
        try:
            parsed_url = urlsplit(database_url)
        except ValueError as error:
            raise ImproperlyConfigured(
                "TURSO_DATABASE_URL must be a valid libsql:// URL."
            ) from error

        if (
            parsed_url.scheme != "libsql"
            or not parsed_url.hostname
            or parsed_url.username
            or parsed_url.password
            or parsed_url.query
            or parsed_url.fragment
        ):
            raise ImproperlyConfigured(
                "TURSO_DATABASE_URL must be a libsql:// endpoint without embedded credentials."
            )
        if not auth_token:
            raise ImproperlyConfigured(
                "TURSO_AUTH_TOKEN is required when using a remote Turso database."
            )

        return {
            "ENGINE": "config.db_backends.turso",
            "NAME": database_url,
            "OPTIONS": {"auth_token": auth_token},
        }

    if auth_token:
        raise ImproperlyConfigured(
            "The matching Turso database URL is required when its auth token is set."
        )
    if environ.get("VERCEL"):
        raise ImproperlyConfigured(
            "Configure stable KIZUNA_TURSO_DATABASE_URL and "
            "KIZUNA_TURSO_AUTH_TOKEN for Production, or TURSO_DATABASE_URL and "
            "TURSO_AUTH_TOKEN for other Vercel environments."
        )

    return {
        "ENGINE": "django.db.backends.sqlite3",
        "NAME": base_dir / "db.sqlite3",
        # The live simulator writes every 2 seconds while users act: WAL, a busy
        # timeout and IMMEDIATE transactions make concurrent writers wait
        # instead of failing with "database is locked".
        "OPTIONS": {
            "timeout": 20,
            "transaction_mode": "IMMEDIATE",
            "init_command": "PRAGMA journal_mode=WAL; PRAGMA synchronous=NORMAL;",
        },
    }


def _get_storages(environ):
    has_read_write_token = bool(
        environ.get("BLOB_READ_WRITE_TOKEN")
        or environ.get("VERCEL_BLOB_READ_WRITE_TOKEN")
    )
    has_oidc_credentials = bool(
        environ.get("BLOB_STORE_ID")
        and (environ.get("VERCEL_OIDC_TOKEN") or environ.get("VERCEL"))
    )
    uses_blob = has_read_write_token or has_oidc_credentials

    if environ.get("VERCEL") and not uses_blob:
        raise ImproperlyConfigured(
            "Configure a private Vercel Blob store for persistent file storage."
        )

    default_backend = (
        "config.blob_storage.PrivateVercelBlobStorage"
        if uses_blob
        else "django.core.files.storage.FileSystemStorage"
    )
    return {
        "default": {"BACKEND": default_backend},
        "staticfiles": {
            "BACKEND": "django.contrib.staticfiles.storage.StaticFilesStorage",
        },
    }


def _get_ice_servers(environ):
    value = environ.get("KIZUNA_ICE_SERVERS", "").strip()
    if not value:
        return [{"urls": "stun:stun.l.google.com:19302"}]
    try:
        servers = json.loads(value)
    except json.JSONDecodeError as error:
        raise ImproperlyConfigured(
            "KIZUNA_ICE_SERVERS must be a JSON list."
        ) from error
    if not isinstance(servers, list) or any(
        not isinstance(server, dict) or not server.get("urls")
        for server in servers
    ):
        raise ImproperlyConfigured(
            "KIZUNA_ICE_SERVERS must be a JSON list of ICE servers."
        )
    return servers


